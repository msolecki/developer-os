#!/bin/sh
# A Poetry + pytest package in git with consistent habits to observe (snake_case modules, one tests/test_<module>.py
# per module, ruff at line length 100, domain errors subclassing ShopError) and one swallowed error.
set -eu
d=${1:-$PWD}
cd "$d"
git init -q -b main
git config user.name eval
git config user.email eval@example.invalid
mkdir -p src/shop tests
cat > pyproject.toml <<'TOML'
[tool.poetry]
name = "sample-shop"
version = "0.1.0"
description = "A sample shop"
authors = ["eval <eval@example.invalid>"]
packages = [{ include = "shop", from = "src" }]

[tool.poetry.dependencies]
python = "^3.12"

[tool.poetry.group.dev.dependencies]
pytest = "^8.3"
ruff = "^0.7"

[tool.ruff]
line-length = 100

[tool.ruff.lint]
select = ["E", "F", "I", "N"]

[tool.pytest.ini_options]
testpaths = ["tests"]
pythonpath = ["src"]

[build-system]
requires = ["poetry-core"]
build-backend = "poetry.core.masonry.api"
TOML
printf '# This file is automatically @generated by Poetry 1.8.4 and should not be changed by hand.\npackage = []\n\n[metadata]\nlock-version = "2.0"\npython-versions = "^3.12"\n' > poetry.lock
: > src/shop/__init__.py
cat > src/shop/errors.py <<'PY'
class ShopError(Exception):
    """Base class of every domain error; `code` is the machine-readable name."""

    code = "SHOP_ERROR"


class EmptyCartError(ShopError):
    code = "CART_EMPTY"


class OrderNotFoundError(ShopError):
    code = "ORDER_NOT_FOUND"
PY
cat > src/shop/cart_total.py <<'PY'
from shop.errors import EmptyCartError


def cart_total(lines: list[dict]) -> int:
    """Sum line totals of a cart in cents."""
    if not lines:
        raise EmptyCartError("the cart has no lines")
    return sum(line["price_cents"] * line["quantity"] for line in lines)
PY
cat > src/shop/order_store.py <<'PY'
from shop.errors import OrderNotFoundError

_ORDERS: dict[str, dict] = {}


def save_order(order_id: str, order: dict) -> None:
    _ORDERS[order_id] = order


def load_order(order_id: str) -> dict:
    try:
        return _ORDERS[order_id]
    except KeyError as err:
        raise OrderNotFoundError(order_id) from err
PY
cat > src/shop/receipt_mailer.py <<'PY'
import smtplib


def send_receipt(address: str, body: str) -> None:
    try:
        with smtplib.SMTP("localhost") as smtp:
            smtp.sendmail("shop@example.invalid", [address], body)
    except Exception:
        pass
PY
cat > tests/test_cart_total.py <<'PY'
import pytest

from shop.cart_total import cart_total
from shop.errors import EmptyCartError


def test_cart_total_sums_line_totals():
    assert cart_total([{"price_cents": 250, "quantity": 2}]) == 500


def test_cart_total_rejects_an_empty_cart():
    with pytest.raises(EmptyCartError):
        cart_total([])
PY
cat > tests/test_order_store.py <<'PY'
import pytest

from shop.errors import OrderNotFoundError
from shop.order_store import load_order, save_order


def test_load_order_returns_the_saved_order():
    save_order("o-1", {"total_cents": 500})
    assert load_order("o-1") == {"total_cents": 500}


def test_load_order_raises_for_an_unknown_id():
    with pytest.raises(OrderNotFoundError):
        load_order("missing")
PY
git add -A
git commit -q -m "feat: cart total, order store and receipts"
